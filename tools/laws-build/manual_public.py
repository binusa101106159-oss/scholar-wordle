def main(outdir):
    path = Path(outdir) / 'pub04-3.json'
    data = json.loads(path.read_text(encoding='utf-8'))
    def cell(text, col): return dict(c=col, cs=1, rs=1, text=text)
    corner = cell('', 0)
    corner['diag'] = dict(n=2, tr='實施期間', mid='比率', bl='任職年資',
                          lines=[[14, 0, 100, 100], [0, 43, 100, 100]],
                          positions=dict(tr=[77, 18], mid=[31, 43], bl=[26, 79]))
    rows = [[corner] + [cell(h, i+1) for i, h in enumerate(HEADERS)]]
    for line in VALUES.splitlines():
        values = line.split()
        assert len(values) == 12
        rows.append([cell(values[0], 0)] + [cell(v+'%', i+1) for i, v in enumerate(values[1:])])
    assert len(rows) == 27
    title = next(b for b in data['blocks'] if b['t'] == 'p' and '附表三' in b['text'])
    data['blocks'] = [title, dict(t='table', widths=[82]+[51]*11, head=1, rows=rows), dict(t='p', text=NOTE)]
    path.write_text(json.dumps(data, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
    print('pub04-3 image-only grid: 26 rows x 11 values; 300-dpi transcription; native table OK')


if __name__ == '__main__': main(sys.argv[1])
